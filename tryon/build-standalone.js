#!/usr/bin/env node
// Bundles the modular core in tryon/src/ into ONE self-contained HTML file.
// `three` is kept external and resolved by the importmap, so the output stays
// small. The bundling logic is exported as buildBundle() so the smoke test can
// exercise the exact same module graph without a browser.
//
// IMPORTANT: the output (tryon/app-bundle.html) uses <script type="module"> +
// an importmap. That runs on real module-capable hosts (GitHub Pages, githack,
// any static server) but NOT on htmlpreview.github.io, which can't execute
// module scripts. The htmlpreview phone-preview deliverable is the hand-built
// classic-script standalone.html at the repo root — this build never touches it.
//
// Usage: node tryon/build-standalone.js   (writes tryon/app-bundle.html)

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'src');
const OUT = path.join(__dirname, 'app-bundle.html');

// Modules in a safe definition order (entry `main` is emitted/run last).
const MODULES = ['proportions', 'materials', 'garments', 'avatar', 'catalog', 'wardrobe', 'ui', 'sync'];
const ENTRY = 'main';

function read(mod) {
  return fs.readFileSync(path.join(SRC, `${mod}.js`), 'utf8');
}

// Transform one module's source: strip ESM import/export syntax, rewrite local
// imports to __require(), and collect exported names.
function transform(code, { isEntry }) {
  const exportNames = [];
  const lines = code.split('\n');
  const out = [];
  for (let line of lines) {
    // Drop the bare `three` / addons imports — THREE & OrbitControls live in the
    // top module scope and are captured by closure.
    if (/^\s*import\s+\*\s+as\s+THREE\s+from\s+['"]three['"]/.test(line)) continue;
    if (/^\s*import\s+\{[^}]*\}\s+from\s+['"]three\/addons\//.test(line)) continue;

    // import * as NS from './file.js'  ->  const NS = __require('file');
    let m = line.match(/^\s*import\s+\*\s+as\s+(\w+)\s+from\s+['"]\.\/(\w+)\.js['"];?/);
    if (m) { out.push(`const ${m[1]} = __require('${m[2]}');`); continue; }

    // import { a, b } from './file.js'  ->  const { a, b } = __require('file');
    m = line.match(/^\s*import\s+\{([^}]*)\}\s+from\s+['"]\.\/(\w+)\.js['"];?/);
    if (m) { out.push(`const {${m[1]}} = __require('${m[2]}');`); continue; }

    // export function/class/const/let NAME  ->  strip `export `, track NAME
    m = line.match(/^\s*export\s+(?:async\s+)?(function|class|const|let|var)\s+(\w+)/);
    if (m) { exportNames.push(m[2]); line = line.replace(/^(\s*)export\s+/, '$1'); }

    out.push(line);
  }
  if (!isEntry) {
    out.push('');
    for (const n of exportNames) out.push(`__exports.${n} = ${n};`);
  }
  return out.join('\n');
}

// Build the JS bundle string (a tiny CJS-style module system + entry).
function buildBundle() {
  let bundle = '';
  bundle += `// AUTO-GENERATED by tryon/build-standalone.js — do not edit by hand.\n`;
  bundle += `// Single source of truth lives in tryon/src/*.js.\n`;
  bundle += `import * as THREE from 'three';\n`;
  bundle += `import { OrbitControls } from 'three/addons/controls/OrbitControls.js';\n\n`;
  bundle += `const __cache = {};\nconst __defs = {};\n`;
  bundle += `function __require(name){ if(__cache[name]) return __cache[name]; const __exports={}; __cache[name]=__exports; __defs[name](__exports); return __exports; }\n\n`;

  for (const mod of MODULES) {
    const body = transform(read(mod), { isEntry: false });
    bundle += `__defs['${mod}'] = function(__exports){\n${body}\n};\n\n`;
  }
  // Entry module runs in the top scope (has access to THREE / OrbitControls / __require).
  bundle += `// ---- entry ----\n` + transform(read(ENTRY), { isEntry: true }) + '\n';
  return bundle;
}

// Assemble the full HTML using tryon/index.html as the template, inlining CSS + JS.
function buildHtml() {
  const bundle = buildBundle();
  let html = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
  const css = fs.readFileSync(path.join(__dirname, 'styles.css'), 'utf8');
  html = html.replace(/<link rel="stylesheet" href="\.\/styles\.css" \/>/,
    `<style>\n${css}\n</style>`);
  html = html.replace(/<script type="module" src="\.\/src\/main\.js"><\/script>/,
    `<script type="module">\n${bundle}\n</script>`);
  return html;
}

module.exports = { buildBundle, buildHtml, transform, MODULES, ENTRY };

// CLI: write the single-file bundle for module-capable hosts.
if (require.main === module) {
  const html = buildHtml();
  fs.writeFileSync(OUT, html);
  console.log(`tryon/app-bundle.html written (${html.length} bytes) — for module-capable hosts, NOT htmlpreview`);
}
